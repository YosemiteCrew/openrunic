/**
 * Charges, claims, remittance, statements and payments. Operational: safe to
 * translate, and worth translating - a front desk collecting a copay is not a
 * clinical decision.
 *
 * ## Two rules this file follows and the English one does not have to
 *
 * Spanish inflects for gender and number, so any sentence that takes a word as
 * a placeholder has to survive whatever that word turns out to be. "3
 * reclamaciones depurada" is what a literal translation of "{count} claims
 * {state}" produces, and it reads as broken to everyone who speaks the
 * language and fine to whoever shipped it. So where English can drop a state
 * word straight into a sentence, the Spanish sentence puts it behind a neutral
 * frame ("con estado {state}") that no inflection can break.
 *
 * The placeholders themselves are exactly the ones the English message has,
 * never more and never fewer. `format` throws on a value the message does not
 * use, and drops nothing quietly when one is missing, so a well-meant rewrite
 * that loses `{amount}` is a red build rather than a receipt with a gap where
 * the money was.
 *
 * Nothing clinical is translated anywhere in this catalogue, here included: a
 * CPT description or an ICD-10 display arrives as data and stays in the words
 * the code system gave it.
 */
