#!/usr/bin/env node
/**
 * THE BROWSER'S SIGN-IN TABLE IS A TRANSCRIPTION OF THE API'S, AND IT IS
 * MAINTAINED BY HAND.
 *
 * `apps/web/src/lib/auth/directory.ts` lists the demo tokens the staff sign-in
 * screen offers, with the identity to put in the top bar for each. Its header
 * says what the copy costs and which half carries the risk:
 *
 *   "The subjects are the load-bearing half: they are what an audit record
 *    attributes an access to, so they must match the API's, not merely look
 *    like it."
 *
 * Nothing checked that. It was checked once by hand, during the #350 review -
 * seven of seven agreeing - and a hand check works exactly once. The two ways
 * it goes wrong are both quiet: a subject that drifts attributes an access to
 * the wrong person in a record nobody can rewrite, and a principal added to the
 * API and not here resolves against the API and cannot be signed in with
 * through the product.
 *
 * ## Why this is in scripts/ci and not in apps/web
 *
 * Not a preference. `apps/web/package.json` names `@openrunic/i18n` and
 * `@openrunic/ui` and no API package at all, so a test in that workspace cannot
 * reach `DEMO_PRINCIPALS` through the module graph however it is written. The
 * bundling argument in `directory.ts`'s header is a reason not to import the
 * API from browser code; this is the reason it is impossible from a test, which
 * never ships. `capability-parity.mjs` is built around the same constraint.
 *
 * ## Why this imports both sides where its neighbour reads one as text
 *
 * `capability-parity.mjs` deliberately reads the browser file as TEXT, because
 * that table is EMITTED: importing both sides would compare the generator with
 * itself, and a role the generator dropped would drop out of the expectation
 * too. That is how a `read-only` role once went missing.
 *
 * This table is written by hand and generated by nothing, so there is no
 * self-comparison to avoid, and importing compares values rather than a regex's
 * opinion of values. IF THIS EVER GROWS AN EMITTER, THAT HAZARD COMES BACK AND
 * one side has to be read by a different route again.
 *
 * ## Why the offered tokens are named and not counted
 *
 * `directory.ts` exports a FUNCTION, not a table, and its arguments decide
 * whether it returns anything: `developmentCredentials('production', false)` is
 * an empty list, and that emptiness is the production sign-in refusal working
 * correctly. A guard phrased as "no disagreements" is satisfied by an empty
 * list, so calling it with the wrong arguments - or a later change to what the
 * arguments mean - would report a clean parity check over nothing at all. The
 * expected tokens are therefore spelled out, on both sides.
 */

import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

/* Resolved from this file, never from the caller's cwd: run from anywhere else
   a repo-relative literal misses, and a missing file reports as drift - the
   same output a genuine divergence produces. */
const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');

/* The readers below take a path and open it; they do not build one. Joining a
   base to an argument inside the sink is the shape a scanner matches on, and
   arguing that the argument is safe does not clear it - the guidance here is to
   remove the variable from the sink rather than to guard it. So the join
   happens once, in `main`, over the two literals above, and
   `capability-parity.mjs` reads its inputs the same way.

   The parameter stays because the guard IMPORTS its inputs: a test that handed
   it a Map would exercise something the guard never does, so the tests point
   these readers at fixture modules written to disk. */
function sourcePath(repoRelative) {
  return resolve(REPO_ROOT, repoRelative);
}

export const API_SOURCE = 'apps/api/src/auth/static-resolver.ts';
export const WEB_SOURCE = 'apps/web/src/lib/auth/directory.ts';

/**
 * The tokens the staff sign-in offers, spelled out.
 *
 * A list rather than a count, because a count reports the same number when a
 * principal is added and when one is dropped, and says nothing about which.
 */
export const OFFERED = [
  'dev-clinician-a',
  'dev-frontdesk-a',
  'dev-biller-a',
  'dev-clinician-b',
  'dev-auditor-a',
  'dev-stockkeeper-a',
  'dev-readonly-a',
];

/**
 * Principals the API publishes and the staff sign-in deliberately does not.
 *
 * `dev-portal-a` is a patient's credential, and this is the staff EMR: a portal
 * token signing in here would reach a shell and a patient list it holds no
 * scopes for and spend the session collecting 403s. Named, because a count
 * cannot tell a second deliberate absence from an accidental deletion.
 */
export const NOT_OFFERED = ['dev-portal-a'];

/** Every demo principal the API's static resolver publishes. */
export async function readApiPrincipals(path) {
  const module = await import(pathToFileURL(path).href);
  return new Map(
    [...module.DEMO_PRINCIPALS].map(([token, principal]) => [
      token,
      {
        subject: principal.subject,
        displayName: principal.displayName,
        roles: [...principal.roles],
      },
    ])
  );
}

/**
 * What the staff sign-in offers, as identities.
 *
 * `'development'` is chosen, and the second argument is deliberately not
 * passed: under any `nodeEnv` other than `'production'` the full table is
 * returned whatever `demoBuild` says, so this call cannot be changed by a flip
 * of that default. Passing `'production'` here - or reaching a state where
 * `'development'` stops meaning "populated" - empties the comparison, and an
 * empty comparison agrees with everything.
 *
 * Two things catch that, and neither is this function: `main` refuses outright
 * when either side reads empty, and `compare` names the tokens it expects, so
 * an empty list fails as seven missing identifiers rather than as silence.
 */
export async function readOfferedCredentials(path) {
  const module = await import(pathToFileURL(path).href);
  return new Map(
    module.developmentCredentials('development').map((credential) => [
      credential.token,
      {
        subject: credential.identity.subject,
        displayName: credential.identity.displayName,
        roles: [...credential.identity.roles],
      },
    ])
  );
}

/**
 * Every way the two tables can disagree, named.
 *
 * Order matters in the message and not in the check: the presence problems come
 * first because a missing token explains every field difference that follows
 * it, and a reader who fixes the fields first has fixed the wrong thing.
 */
export function compare({
  api,
  offered,
  expectedOffered = OFFERED,
  expectedNotOffered = NOT_OFFERED,
}) {
  const problems = [];

  const offeredTokens = [...offered.keys()].sort();
  const expected = [...expectedOffered].sort();
  if (offeredTokens.join('\n') !== expected.join('\n')) {
    for (const token of expected.filter((t) => !offered.has(t))) {
      problems.push(`${token}: expected on the staff sign-in and it is not offered`);
    }
    for (const token of offeredTokens.filter((t) => !expected.includes(t))) {
      problems.push(`${token}: offered by the staff sign-in and not in the expected list`);
    }
  }

  const apiOnly = [...api.keys()].filter((token) => !offered.has(token)).sort();
  const expectedApiOnly = [...expectedNotOffered].sort();
  if (apiOnly.join('\n') !== expectedApiOnly.join('\n')) {
    for (const token of apiOnly.filter((t) => !expectedApiOnly.includes(t))) {
      problems.push(
        `${token}: published by the API and offered by nothing - deliberate, or dropped?`
      );
    }
    for (const token of expectedApiOnly.filter((t) => !apiOnly.includes(t))) {
      problems.push(`${token}: expected to be withheld from the staff sign-in and it is not`);
    }
  }

  for (const token of offeredTokens) {
    const mine = offered.get(token);
    const theirs = api.get(token);
    if (theirs === undefined) {
      problems.push(`${token}: offered by the staff sign-in and unknown to the API - it would 401`);
      continue;
    }
    /* The subject first, and named as what it is. A drifted subject is not a
       cosmetic difference: it is the value an audit record attributes an access
       to, and the record cannot be rewritten afterwards. */
    if (mine.subject !== theirs.subject) {
      problems.push(
        `${token}: subject ${mine.subject} does not match the API's ${theirs.subject} - this is the audit attribution key`
      );
    }
    if (mine.displayName !== theirs.displayName) {
      problems.push(
        `${token}: displayName ${JSON.stringify(mine.displayName)} does not match the API's ${JSON.stringify(theirs.displayName)}`
      );
    }
    if (mine.roles.join(',') !== theirs.roles.join(',')) {
      problems.push(
        `${token}: roles [${mine.roles.join(', ')}] do not match the API's [${theirs.roles.join(', ')}]`
      );
    }
  }

  return { problems };
}

async function main() {
  let api;
  let offered;
  try {
    api = await readApiPrincipals(sourcePath(API_SOURCE));
    offered = await readOfferedCredentials(sourcePath(WEB_SOURCE));
  } catch (error) {
    process.stderr.write(`demo-principal-parity: a source could not be read: ${error.message}\n`);
    return 1;
  }

  /* The rail read something. Both sides come from a function or a table that
     can legitimately be empty - `developmentCredentials` returns [] under
     production arguments - and an empty comparison agrees with everything. */
  if (api.size === 0 || offered.size === 0) {
    process.stderr.write(
      `demo-principal-parity: read ${api.size} API principals and ${offered.size} offered credentials; ` +
        `a side that is empty agrees with everything, so this is a guard that did not run.\n`
    );
    return 1;
  }

  const { problems } = compare({ api, offered });
  if (problems.length === 0) {
    process.stdout.write(
      `demo-principal-parity: ${offered.size} staff credentials match the API on subject, display name and roles; ` +
        `${NOT_OFFERED.join(', ')} withheld by design.\n`
    );
    return 0;
  }

  /*
   * WHY IT IS SAFE FOR THIS MESSAGE TO PRINT SUBJECTS AND DISPLAY NAMES.
   *
   * A scanner flags identity fields reaching a CI log, and the shape is real.
   * The reason it is safe is not that these are demo values. It is the read
   * surface: THIS GUARD'S ENTIRE ABILITY TO READ ANYTHING IS TWO DYNAMIC
   * IMPORTS. No `readFileSync`, no `fetch`, no `process.env`, no subprocess -
   * checkable in one grep, and it does not depend on which two paths are
   * passed.
   *
   * The precise bound is one layer in, and it is tighter than "two files":
   * `import()` evaluates the whole graph, so the bound is only as good as what
   * those two modules import. Both import exactly one thing and both are
   * `import type`, which strip-types erases:
   *
   *   static-resolver.ts   import type { Principal, PrincipalResolver }
   *   directory.ts         import type { Identity }
   *
   * Measured rather than read off the line - copy both files somewhere with no
   * siblings, no package.json and no node_modules, and they still load: 8
   * principals and 7 credentials. **The graph is empty.** Each produces a table
   * and performs no I/O: a `Map` of principals, and an array built by a pure
   * `.map` over literal rows.
   *
   * So the trigger a reader can actually check: **this bound holds while both
   * files' only imports are `import type`.** A value import appearing in either
   * one makes this guard's exposure that module's entire graph, and unlike "if
   * it ever reads something new" that is one grep and it is visible in a diff.
   *
   * It prints the WORKING TREE, not the commit - Claude L3 drove a failure and
   * traced the values, and a planted mutant subject present in no commit came
   * out of the message. That is worth knowing and it is not an exposure: in CI
   * the tree is the checkout, so tree and commit coincide and nothing is
   * published that a clone does not carry; locally the output goes to the
   * terminal of whoever is already holding that tree. Said explicitly because
   * the caveat alone reads like a risk, and the repair someone would reach for
   * is truncating the identifiers - which costs the only thing that makes the
   * message actionable.
   *
   * They are printed rather than counted because naming the drifted subject is
   * the entire point: "this is the audit attribution key" is what makes a
   * reader act, and "one field differs" is not.
   */
  process.stderr.write(
    `demo-principal-parity: ${WEB_SOURCE} disagrees with ${API_SOURCE}.\n` +
      problems.map((problem) => `  ${problem}\n`).join('') +
      `\nThese two tables are transcribed by hand. The subjects are what an audit record attributes an access to.\n`
  );
  return 1;
}

if (process.argv[1] && import.meta.filename === process.argv[1]) {
  process.exit(await main());
}
